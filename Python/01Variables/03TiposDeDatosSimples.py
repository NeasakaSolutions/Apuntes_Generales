# Strings - Cadenas de texto:
# Se pueden utilizar comillas simples y dobles siempre y cuando se respete la sigueinte sintaxis:
print('Esto es un string, "Esto es un string entre doble comillas"') 

# Numero entero: (int)
numero_uno = 10
#Numero decimal: (float)
numero_dos = 10.1

# Impresion de resultados con f string, f string sirvepara combinar tipos de datos en los print
print(f"Numero entero: {numero_uno}")
print(f"Numero decimal: {numero_dos}")

# Impresion del tipo de dato:
print(f"El numero {numero_uno} es del tipo: {type(numero_uno)}")
print(f"El numero {numero_dos} es del tipo: {type(numero_dos)}")

